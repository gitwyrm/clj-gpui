(def catppuccin-violet
  (theme/theme-set
   {:name "Catppuccin Violet"
    :author "utility_belt_gpui"
    :url "https://github.com/gitwyrm/utility_belt_gpui"
    :themes [{:name "Catppuccin Violet Light"
              :mode :light
              :colors light-colors}
             {:name "Catppuccin Violet Dark"
              :mode :dark
              :colors dark-colors}]}))

(def light
  (first (:themes catppuccin-violet)))

(def dark
  (second (:themes catppuccin-violet)))

;; Re-run on `(require ns :reload)` so palette edits reach the host.
(theme/register! catppuccin-violet)
